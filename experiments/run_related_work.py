FULL_CONFIG = ROOT / "configs/full_sweep.yaml"
PROTOCOL = ROOT / "configs/related_work.yaml"
REPLAY_METHODS = ("B1_full_replication", "B5_freshness_aware_uncoded_caching", "B7_proposed_algorithm1_algorithm2")
PILOT_METHODS = ("B5_freshness_aware_uncoded_caching", "B7_proposed_algorithm1_algorithm2",
                 "B7_runtime_rank_aware", "B8_static_rlnc_fountain", "B9_contact_frequency_coded",
                 "A1_no_trajectory", "A2_no_rank_aware")
FULL_METHODS = ("B8_static_rlnc_fountain", "B9_contact_frequency_coded")
SUBSETS = {
    "S1_opportunity": {"ttl_s": 1200.0, "placement_capacity_bytes": 96, "packet_loss": 0.0},
    "S2_stress": {"ttl_s": 300.0, "placement_capacity_bytes": 24, "packet_loss": 0.10},
    "S3_middle": {"ttl_s": 600.0, "placement_capacity_bytes": 48, "packet_loss": 0.05},
}
SEEDS = [101, 137, 173, 211, 257]


def file_sha(path):
    h = hashlib.sha256()
    with Path(path).open("rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""): h.update(b)
    return h.hexdigest()


def atomic_json(path, value):
    path = Path(path); path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_name(path.name + ".tmp")
    temp.write_text(json.dumps(value, indent=2, sort_keys=True, allow_nan=False) + "\n")
    temp.replace(path)


def source_identity(spec):
    files = sorted([*ROOT.glob("src/tacp_sim/*.py"),
                    ROOT / "experiments/run_related_work.py", ROOT / "experiments/run_sweep.py",
                    ROOT / "experiments/run_phase4_ci.py", ROOT / "scripts/validate_related_work.py"])
    code = {str(p.relative_to(ROOT)): file_sha(p) for p in files}
    return {
        "trace_sha256": file_sha(ROOT / spec["trace_path"]),
        "provenance_sha256": file_sha(ROOT / spec["trace_provenance_path"]),
        "rsu_map_sha256": file_sha(ROOT / spec["rsu_rules"]["map_path"]),
        "code_sha256": sha(code),
    }, code


def resolved(cell):
    out = {k: v for k, v in cell.items() if not k.startswith("_")}
    for k in ("trace_path", "trace_provenance_path"):
        out[k] = str((ROOT / out[k]).resolve())
    return out


def prepare(mode, partitions=1, partition_index=0):
    spec = load_config(FULL_CONFIG)
    protocol = load_config(PROTOCOL)
    if (protocol.get("frozen") is not True or protocol["seeds"] != SEEDS
            or protocol["subsets"] != SUBSETS
            or protocol["replay_methods"] != list(REPLAY_METHODS)
            or protocol["pilot_methods"] != list(PILOT_METHODS)
            or protocol["full_methods"] != list(FULL_METHODS)):
        raise ValueError("runner and frozen protocol disagree")
    gate = stability(spec, FULL_CONFIG)
    frozen, norm = make_plan(spec, FULL_CONFIG)
    grid = cells(norm)
    by_subset = {s: [] for s in SUBSETS}
    for i, c in enumerate(grid):
        for s, match in SUBSETS.items():
            if all(float(c[k]) == float(v) for k, v in match.items()):
                by_subset[s].append((i, s, c))
    if any(len(x) != 18 for x in by_subset.values()): raise ValueError("expected 18 cells per subset")
    if mode == "replay":
        selection = [by_subset["S3_middle"][0]]
        seeds, vlim, methods = SEEDS, 255, REPLAY_METHODS
    elif mode == "dry-run":
        selection = [items[0] for items in by_subset.values()]
        seeds, vlim, methods = SEEDS[:2], 2, PILOT_METHODS
    elif mode == "pilot":
        selection = [item for items in by_subset.values() for item in items]
        seeds, vlim, methods = SEEDS, 255, PILOT_METHODS
    elif mode == "full":
        selection = [(i, next((s for s, m in SUBSETS.items() if all(float(c[k]) == float(v) for k, v in m.items())), "outside_prespecified_subsets"), c) for i, c in enumerate(grid)]
        seeds, vlim, methods = SEEDS, 255, FULL_METHODS
    else: raise ValueError(mode)
    if partitions < 1 or not 0 <= partition_index < partitions: raise ValueError("invalid partition")
    sources, code_files = source_identity(spec)
    if frozen["full_plan_hash"] != protocol["full_plan_hash"]:
        raise ValueError("frozen full-plan identity mismatch")
    for name, expected in protocol["source_hashes"].items():
        if file_sha(ROOT / name) != expected: raise ValueError(f"frozen source mismatch: {name}")
    w, provenance = _load_windows(resolved(selection[0][2]), seeds[0])
    all_vehicles = _trace_vehicle_ids(w, {**spec, "trace_vehicle_limit": 255})
    if len(all_vehicles) != 255: raise ValueError("frozen vehicle sample differs")
    # Deterministic two-vehicle dry-run sample, favoring nontrivial revisit traces
    # using contact count only (no method outcomes).
    windows_by_vehicle = {vid: [x for x in w if str(x.vehicle_id) == vid] for vid in all_vehicles}
    if mode == "dry-run":
        vehicles = sorted(all_vehicles, key=lambda v: (-len(windows_by_vehicle[v]), v))[:vlim]
        if vehicles != protocol["dry_run"]["vehicle_ids"]: raise ValueError("dry-run vehicle selection changed")
    else: vehicles = all_vehicles[:vlim]
    universe = sorted(str(x["rsu_id"]) for x in json.loads((ROOT / spec["rsu_rules"]["map_path"]).read_text())["rsus"])
    identity = {"schema": "tacp-related-work-v2", "mode": mode,
                "protocol_hash": sha(protocol), "full_plan_hash": frozen["full_plan_hash"],
                "source_hashes": sources, "seeds": seeds, "methods": list(methods),
                "vehicle_ids": vehicles, "episodes_per_seed": 1,
                "cell_ids": [c["_sweep_cell_id"] for _, _, c in selection]}
    plan = {**identity, "run_hash": sha(identity), "code_files": code_files,
            "full_selected_cells": len(selection), "full_expected_rows": len(selection)*len(seeds)*len(vehicles)*len(methods),
            "partition_index": partition_index, "partitions": partitions,
            "rsu_universe": universe, "legacy_stability_gate": gate}
    selected = [v for index, v in enumerate(selection) if index % partitions == partition_index]
    if not selected: raise ValueError("empty partition")
    plan["selected_cell_ids"] = [c["_sweep_cell_id"] for _, _, c in selected]
    plan["selected_cells"] = len(selected)
    plan["expected_rows"] = len(selected)*len(seeds)*len(vehicles)*len(methods)
    budget_key = "dry_run" if mode == "dry-run" else mode
    if (plan["full_expected_rows"] != protocol["budget"][budget_key+"_rows"]
            or plan["full_selected_cells"] != protocol["budget"][budget_key+"_cells"]):
        raise ValueError("frozen row/cell budget mismatch")
    return plan, selected, windows_by_vehicle, w, provenance


def check_launch_gates(plan, replay_gate, dry_gate, pilot_gate):
    required_budgets = {"replay": (1, 3825), "dry-run": (3, 84), "pilot": (54, 481950)}
    for phase, path in (("replay", replay_gate), ("dry-run", dry_gate), ("pilot", pilot_gate)):
        if path is None: raise ValueError(f"full requires {phase} validation artifact")
        g = json.loads(Path(path).read_text())
        passed = g.get("passed", g.get("gate", {}).get("passed", False))
        if passed is not True: raise ValueError(f"{phase} gate is not passed")
        required_cells, required_rows = required_budgets[phase]
        if (g.get("schema") != "tacp-related-work-validation-v2"
                or g.get("complete") is not True or g.get("registered_scale") is not True
                or g.get("completed_cells") != required_cells or g.get("expected_cells") != required_cells
                or g.get("actual_rows") != required_rows or g.get("expected_rows") != required_rows
                or g.get("gate", {}).get("technical_passed") is not True
                or g.get("gate", {}).get("stability_passed") is not True):
            raise ValueError(f"{phase} gate does not certify the complete registered experiment")
        for k in ("protocol_hash", "full_plan_hash", "source_hashes"):
            value = g.get(k, g.get("identity", {}).get(k))
            if value != plan[k]: raise ValueError(f"{phase} {k} mismatch")
        if g.get("mode") != phase: raise ValueError(f"wrong mode in {phase} gate")
        if not g.get("input_sha256"): raise ValueError(f"{phase} gate missing input hashes")
        for input_path, expected in g["input_sha256"].items():
            if file_sha(input_path) != expected: raise ValueError(f"{phase} validated input changed")


def simulate_row(cell, windows, plan, seed, vehicle_id):
    cfg = resolved(cell); cfg["vehicle_id"] = vehicle_id
    obj = _object_from_config(cfg)
    if plan.coded:
        run_obj = obj; placement = plan.placement
    else:
        run_obj = replace(obj, n=1, k=1)
        cfg.update(n=1, k=1)
        placement = {rsu: [0] for rsu, ids in plan.placement.items() if ids}
    result = Simulation(cfg, seed).run_episode(
        0, windows=windows, placement_override=placement, object_override=run_obj,
        symbol_vectors=plan.metadata.get("symbol_vectors"),
        rank_aware_requests=bool(plan.metadata.get("rank_aware_requests", False)),
    )
    tx = result.transmissions
    duplicate = sum(t.failure_reason == "duplicate_or_dependent" for t in tx)
    stale = sum(t.failure_reason == "stale_version" or t.end_time > obj.expires_at for t in tx)
    fresh = bool(result.fresh_success)
    return {
        "cell_id": cell["_sweep_cell_id"], "config_hash": cell["_sweep_cell_id"],
        "baseline": plan.name, "seed": seed, "episode": 0, "vehicle_id": vehicle_id,
        **{k: cell[k] for k in ("object_bytes", "n", "k", "ttl_s", "packet_loss", "placement_capacity_bytes", "rsu_failure_probability")},
        "fresh_success": fresh, "T_decode": result.t_decode, "t_decode": result.t_decode,
        "rank": result.rank, "effective_k": run_obj.k,
        "rank_deficit_at_expiry": max(0, run_obj.k-result.rank),
        "rank_deficit_fraction": max(0, run_obj.k-result.rank)/run_obj.k,
        "transmissions": len(tx), "tx_bytes": sum(t.bytes for t in tx),
        "duplicate_dependent": duplicate,
        "duplicate_dependent_ratio": duplicate/len(tx) if tx else 0.0,
        "stale_on_arrival": stale, "stale_on_arrival_ratio": stale/len(tx) if tx else 0.0,
        "storage": plan.storage_bytes, "backhaul": result.backhaul,
        "migration": result.migration, "repair": result.repair,
        "trace_windows": len(windows), "code_seed_hash": plan.metadata.get("code_seed_hash"),
        "placement_hash": sha(plan.placement),
    }


def run(args):
    started = time.time()
    plan, selected, by_vehicle, all_windows, provenance = prepare(args.mode, args.partitions, args.partition_index)
    output = args.output.resolve(); checkpoint = Path(str(output)+".jsonl")
    if args.plan_only:
        if output.exists() or checkpoint.exists(): raise FileExistsError("plan output already exists")
        atomic_json(output, {"plan_only": True, "plan": plan}); return
    if args.mode == "full": check_launch_gates(plan, args.replay_gate, args.dry_gate, args.pilot_gate)
    if (output.exists() or checkpoint.exists()) and not args.resume: raise FileExistsError("use --resume or a new output")
    output.parent.mkdir(parents=True, exist_ok=True)
    expected_per_cell = len(plan["seeds"])*len(plan["vehicle_ids"])*len(plan["methods"])
    done = {}
    if checkpoint.exists():
        with checkpoint.open() as f:
            for line in f:
                r = json.loads(line)
                if r.get("run_hash") != plan["run_hash"]: raise ValueError("checkpoint identity mismatch")
                cid = r["cell_id"]
                if cid not in plan["selected_cell_ids"] or cid in done: raise ValueError("unexpected/duplicate checkpoint cell")
                if len(r.get("rows", [])) != expected_per_cell: raise ValueError("partial cell checkpoint")
                done[cid] = {k: r[k] for k in ("cell_id", "cell_index", "subset", "row_count")}
    # Precompute leave-one-vehicle-out calibration once; none of the target's
    # windows enter its frequency prior. Placement does not see target RSU IDs.
    calibration = {vid: [w for w in all_windows if str(w.vehicle_id) != vid] for vid in plan["vehicle_ids"]}
    for cell_index, subset, cell in selected:
        cid = cell["_sweep_cell_id"]
        if cid in done: continue
        rows = []; cell_started = time.time(); obj = _object_from_config(cell)
        capacity = int(cell["placement_capacity_bytes"])
        for vid in plan["vehicle_ids"]:
            windows = by_vehicle[vid]
            # Avoid constructing the bounded exponential B6 oracle for an
            # experiment that never evaluates B6. These plans do not use seed.
            seeded_methods = {"B8_static_rlnc_fountain", "A1_no_trajectory"}
            base = {m: build_baseline(m, obj, windows, capacity,
                    calibration_windows=calibration[vid], rsu_universe=plan["rsu_universe"])
                    for m in plan["methods"] if m not in seeded_methods}
            for seed in plan["seeds"]:
                plans = dict(base)
                for method in plan["methods"]:
                    if method in seeded_methods:
                        plans[method] = build_baseline(method, obj, windows, capacity,
                            rsu_universe=plan["rsu_universe"], experiment_seed=seed)
                for method in plan["methods"]:
                    row = simulate_row(cell, windows, plans[method], seed, vid)
                    row["subset"] = subset; rows.append(row)
        record = {k: plan[k] for k in ("schema", "mode", "run_hash", "protocol_hash", "full_plan_hash", "source_hashes")}
        record.update(cell_id=cid, cell_index=cell_index, subset=subset,
                      config={k:v for k,v in cell.items() if not k.startswith("_")},
                      rows=rows, row_count=len(rows), elapsed_s=time.time()-cell_started)
        if len(rows) != expected_per_cell: raise ValueError("row budget mismatch")
        with checkpoint.open("a") as f:
            f.write(json.dumps(record, sort_keys=True, allow_nan=False)+"\n"); f.flush(); os.fsync(f.fileno())
        done[cid] = {k: record[k] for k in ("cell_id", "cell_index", "subset", "row_count")}
        print(json.dumps({"cell_id":cid, "completed_cells":len(done), "selected_cells":len(selected), "elapsed_s":round(time.time()-cell_started,3)}), flush=True)
    result = {"schema":"tacp-related-work-result-v2", "mode":args.mode, "plan":plan,
              "checkpoint":str(checkpoint), "actual_rows":sum(x["row_count"] for x in done.values()),
              "records":list(done.values()), "elapsed_s":time.time()-started, "trace_provenance":provenance}
    if result["actual_rows"] != plan["expected_rows"]: raise ValueError("total budget mismatch")
    atomic_json(output,result)
    print(json.dumps({"output":str(output),"actual_rows":result["actual_rows"],"elapsed_s":result["elapsed_s"]}),flush=True)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--mode",choices=("replay","dry-run","pilot","full"),required=True)
    p.add_argument("--output",type=Path,required=True)
    p.add_argument("--partitions",type=int,default=1)
    p.add_argument("--partition-index",type=int,default=0)
    p.add_argument("--resume",action="store_true")
    p.add_argument("--plan-only",action="store_true")
    p.add_argument("--dry-gate",type=Path)
    p.add_argument("--pilot-gate",type=Path)
    p.add_argument("--replay-gate",type=Path)
    run(p.parse_args())

if __name__ == "__main__": main()
